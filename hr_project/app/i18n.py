def translate(key, lang="az"):
    entry = TRANSLATIONS.get(key)
    if not entry:
        return key
    return entry.get(lang, entry.get("az", key))


def current_lang():
    """Same language-resolution logic as app/__init__.py:inject_globals,
    for use in route handlers that need a translated string outside of a
    template context (e.g. building a dict passed to the template, or a
    flash message)."""
    from flask import current_app, session
    from flask_login import current_user

    lang = session.get("language", current_app.config["DEFAULT_LANGUAGE"])
    if current_user.is_authenticated:
        lang = current_user.language or lang
    return lang
